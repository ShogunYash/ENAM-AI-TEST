"""B1: ingest BSE announcements + EOD prices for the portfolio into data/finn.sqlite.

  uv run python -m scripts.ingest                 # incremental, 60-day window on first run
  uv run python -m scripts.ingest --days 90 --skip-prices
  uv run python -m scripts.ingest --only CERA,TITAN

Also writes docs/bse-subcategories.md: the real (CATEGORYNAME, SUBCATNAME) inventory that B2's
rule-based classifier is built from.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

from app import db, universe
from app.ingest import bse as bse_mod
from app.ingest import prices as prices_mod

ROOT = Path(__file__).resolve().parents[2]
PORTFOLIO = ROOT / "data" / "portfolio.json"
INVENTORY_MD = ROOT / "docs" / "bse-subcategories.md"


def write_inventory() -> int:
    with db.connect() as con:
        rows = con.execute(
            "SELECT category_name, subcategory, COUNT(*) AS n, COUNT(DISTINCT symbol) AS stocks, "
            "MIN(headline) AS example FROM filings GROUP BY category_name, subcategory ORDER BY n DESC").fetchall()
        total = con.execute("SELECT COUNT(*) FROM filings").fetchone()[0]
    lines = [
        "# BSE subcategory inventory (generated by `scripts/ingest.py`)", "",
        (f"{total} filings across the portfolio. This is the ground truth for the T0 rule mapping in "
        "`app/pipeline/classify.py` (B2). Regenerate by re-running ingest."), "",
        "| n | stocks | CATEGORYNAME | SUBCATNAME | example headline |", "|---:|---:|---|---|---|"]
    for r in rows:
        ex = (r["example"] or "").replace("|", "/")[:90]
        lines.append(f"| {r['n']} | {r['stocks']} | {r['category_name'] or '—'} | {r['subcategory'] or '—'} | {ex} |")
    INVENTORY_MD.write_text("\n".join(lines) + "\n", "utf-8")
    return len(rows)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=60)
    ap.add_argument("--only", help="comma-separated NSE symbols")
    ap.add_argument("--scope", choices=["all", "portfolio", "watchlist"], default="all",
                    help="which group to ingest (default: portfolio + watchlist)")
    ap.add_argument("--skip-bse", action="store_true")
    ap.add_argument("--skip-prices", action="store_true")
    a = ap.parse_args()

    group = {"all": universe.universe(), "portfolio": universe.portfolio(), "watchlist": universe.watchlist()}[a.scope]
    pf = [{"nse_symbol": c.symbol, "bse_scrip_code": c.bse_code} for c in group]
    if a.only:
        wanted = {s.strip().upper() for s in a.only.split(",")}
        pf = [s for s in pf if s["nse_symbol"] in wanted]
    failures = 0

    if not a.skip_bse:
        client = bse_mod.BseClient()
        print(f"BSE: {len(pf)} stocks, {a.days}-day window, incremental")
        for s in pf:
            try:
                fetched, new = bse_mod.ingest_symbol(client, s["nse_symbol"], s["bse_scrip_code"], a.days)
                print(f"  [ok]   {s['nse_symbol']:<11} fetched {fetched:>3}  new {new:>3}")
            except bse_mod.BseError as e:
                failures += 1
                print(f"  [FAIL] {s['nse_symbol']:<11} {e}")
        client.close()
        print(f"inventory: {write_inventory()} distinct (category, subcategory) -> {INVENTORY_MD.relative_to(ROOT)}")

    if not a.skip_prices:
        syms = [s["nse_symbol"] for s in pf]
        bars = prices_mod.fetch_bars(syms)
        missing = [s for s in syms if s not in bars]
        n = prices_mod.store_bars(bars)
        print(f"prices: {len(bars)}/{len(syms)} symbols, {n} bars stored" + (f"; MISSING {missing}" if missing else ""))
        failures += len(missing)
        try:
            n_in = prices_mod.store_intraday(prices_mod.fetch_intraday(syms))
            print(f"intraday: {n_in} 15-minute bars stored (price charts)")
        except Exception as e:  # noqa: BLE001 - charts fall back to daily bars; never fail the ingest for them
            print(f"intraday: skipped ({type(e).__name__})")
        snaps = prices_mod.snapshots(syms)
        for sn in sorted(snaps, key=lambda x: -abs(x.pct_1d))[:5]:
            print(f"   top mover {sn.symbol:<11} {sn.pct_1d:+6.2f}%  vol x{sn.vol_ratio:.2f}  close {sn.close}")

    with db.connect() as con:
        cats = Counter(r["category_name"] for r in con.execute("SELECT category_name FROM filings"))
        print("filings by BSE category:", dict(cats.most_common(6)))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
